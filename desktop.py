# -*- coding: utf-8 -*-
"""表计安装点填表器 · 桌面客户端（pywebview + WebView2）。

双击 exe 打开原生窗口；导出时调用 Excel 写模板，并弹出原生“另存为”。
"""
import base64
import ctypes
import datetime
import os
import pathlib
import sys
import tempfile
import time

import webview

from excel_export import fill_template, template_options

# WebView2 的窗口遮挡计算会导致拖动窗口时假死，关闭该特性
os.environ.setdefault(
    "WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS",
    "--disable-features=CalculateNativeWinOcclusion",
)

LOG_PATH = os.path.join(tempfile.gettempdir(), "meter-filler.log")


def log(message):
    try:
        with open(LOG_PATH, "a", encoding="utf-8") as f:
            f.write("%s %s\n" % (time.strftime("%H:%M:%S"), message))
    except Exception:
        pass


_MUTEX = None


def focus_existing_window():
    """已有实例时把它的窗口提到前面。"""
    user32 = ctypes.windll.user32
    hwnd = user32.FindWindowW(None, "表计安装点填表器")
    if not hwnd:
        return
    user32.ShowWindow(hwnd, 9)  # SW_RESTORE
    user32.SetWindowPos(hwnd, -1, 0, 0, 0, 0, 0x0001 | 0x0002)  # TOPMOST
    user32.SetWindowPos(hwnd, -2, 0, 0, 0, 0, 0x0001 | 0x0002)  # NOTOPMOST
    user32.SetForegroundWindow(hwnd)


def single_instance():
    """同一时间只允许一个实例，避免 WebView2 数据目录被占用导致卡死。"""
    global _MUTEX
    kernel32 = ctypes.windll.kernel32
    _MUTEX = kernel32.CreateMutexW(None, False, "Local\\MeterInstallFormFiller")
    if kernel32.GetLastError() == 183:  # ERROR_ALREADY_EXISTS
        focus_existing_window()
        return False
    return True


def resource_root():
    if getattr(sys, "frozen", False):
        return getattr(sys, "_MEIPASS", os.path.dirname(sys.executable))
    return os.path.dirname(os.path.abspath(__file__))


def default_name(ext):
    stamp = datetime.datetime.now().strftime("%Y%m%d_%H%M")
    return "房产表计安装点导入_%s.%s" % (stamp, ext)


class Api:
    def __init__(self):
        self.window = None

    def template_options(self, payload):
        try:
            data = base64.b64decode(payload["template"])
            result = template_options(data)
            log("template_options ok")
            return result
        except Exception as exc:  # noqa: BLE001
            log("template_options error: %s" % exc)
            return {"error": str(exc)}

    def export_xls(self, payload):
        log("export start rows=%d" % len(payload.get("rows") or []))
        try:
            data = fill_template(
                base64.b64decode(payload["template"]),
                payload.get("sheetName") or "Sheet0",
                int(payload.get("headerRow") or 1),
                payload["rows"],
                int(payload["floorCol"]) if payload.get("floorCol") else None,
                int(payload["roomCol"]) if payload.get("roomCol") else None,
            )
        except Exception as exc:  # noqa: BLE001
            log("export error: %s" % exc)
            return {"ok": False, "error": str(exc)}

        log("export generated bytes=%d" % len(data))
        path = self._ask_save(default_name("xls"))
        if not path:
            log("export canceled at save dialog")
            return {"ok": False, "canceled": True}
        try:
            with open(path, "wb") as f:
                f.write(data)
        except Exception as exc:  # noqa: BLE001
            log("export write error: %s" % exc)
            return {"ok": False, "error": str(exc)}
        log("export saved: %s" % path)
        return {"ok": True, "path": path}

    def save_file(self, content, filename):
        log("save_file start: %s" % filename)
        path = self._ask_save(filename or default_name("xlsx"))
        if not path:
            log("save_file canceled")
            return {"ok": False, "canceled": True}
        try:
            with open(path, "wb") as f:
                f.write(base64.b64decode(content))
        except Exception as exc:  # noqa: BLE001
            log("save_file error: %s" % exc)
            return {"ok": False, "error": str(exc)}
        log("save_file saved: %s" % path)
        return {"ok": True, "path": path}

    def _ask_save(self, filename):
        result = self.window.create_file_dialog(
            webview.FileDialog.SAVE,
            save_filename=filename,
            file_types=("Excel 文件 (*.xls;*.xlsx)", "所有文件 (*.*)"),
        )
        if not result:
            return None
        if isinstance(result, (list, tuple)):
            return result[0] if result else None
        return result


def main():
    if not single_instance():
        log("another instance is running, exit")
        return
    log("app start")
    api = Api()
    window = webview.create_window(
        "表计安装点填表器",
        pathlib.Path(resource_root(), "index.html").as_uri(),
        js_api=api,
        width=1280,
        height=880,
        min_size=(1080, 700),
        text_select=True,
        easy_drag=False,
    )
    api.window = window
    log("window created")
    webview.start(debug=False)
    log("app exit")


if __name__ == "__main__":
    main()


